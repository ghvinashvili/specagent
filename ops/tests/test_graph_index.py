"""graph_index.py (spec A3): graphify's flat wiki export becomes a layered index (one line per top folder or package,
one page per folder with one line per community, then the articles), and no page it writes is over 12,000 bytes. The
script runs as a command, as the other tests of ops/ run theirs."""

import re
import subprocess
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "graph_index.py"
MARK = "<!-- built by ops/graph_index.py; do not edit by hand -->"
FOOTER = "---\n\n*Part of the graphify knowledge wiki. See [index](index.md) to navigate.*"
LINK = re.compile(r"\]\(([^)\s]+)\)")


def run(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-I", str(SCRIPT), *args], cwd=root, capture_output=True, text=True, check=False
    )


def community(label: str, nodes: int, sources: list[str], links: tuple[str, ...] = ()) -> str:
    """A community's article as graphify 0.9.64 writes it: no final newline, a source path only when the node has one."""
    concepts = [
        f"- **{label}{i}()** ({30 - i} connections)" + (f" — `{src}`" if src else "") for i, src in enumerate(sources)
    ]
    related = [f"- [{Path(target).stem}]({target}) (3 shared connections)" for target in links]
    head = ["# " + label, "", f"> {nodes} nodes · cohesion 0.25", "", "## Key Concepts", "", *concepts, ""]
    tail = ["## Relationships", "", *(related or ["- No strong cross-community connections detected"]), "", FOOTER]
    return "\n".join(head + tail)


def god(label: str, degree: int, source: str, home: str) -> str:
    """A god node's article as graphify 0.9.64 writes it (the source may be empty)."""
    return "\n".join(
        [
            "# " + label,
            "",
            f"> God node · {degree} connections · `{source}`",
            "",
            f"**Community:** [{home}]({home}.md)",
            "",
            FOOTER,
        ]
    )


def export(root: Path, articles: dict[str, str]) -> Path:
    """graphify's flat export in root/wiki/graph: its index.md, then the articles."""
    wiki = root / "wiki" / "graph"
    wiki.mkdir(parents=True)
    (wiki / "index.md").write_text("# Knowledge Graph Index\n\n> Auto-generated by graphify.\n", encoding="utf-8")
    for name, text in articles.items():
        (wiki / name).write_text(text, encoding="utf-8")
    return wiki


def dead_links(wiki: Path) -> list[str]:
    """Every relative link of every page under wiki that opens no file."""
    dead = []
    for page in sorted(wiki.rglob("*.md")):
        for target in LINK.findall(page.read_text(encoding="utf-8")):
            if "://" not in target and not (page.parent / target).is_file():
                dead.append(f"{page.relative_to(wiki)} -> {target}")
    return dead


def flat_articles() -> dict[str, str]:
    """Six communities in five folders, two god nodes and a page graphify did not write."""
    core = "packages/a/src/a/core.py"
    return {
        "core.md": community("core", 40, [core, core, core, "docs/guide.md"], links=("guide.md",)),
        "tests_of_core.md": community("tests of core", 12, ["packages/a/tests/test_core.py"] * 2),
        "guide.md": community("guide [draft]", 9, ["docs/guide.md", "docs/howto/one.md"], links=("core.md",)),
        "helpers.md": community("helpers", 5, ["packages/b/helpers.py"]),
        "noxfile.md": community("noxfile", 3, ["noxfile.py"]),
        "loose.md": community("loose", 2, ["", ""]),
        "core_2.md": god("core", 30, core, "core"),  # graphify's name for a god node labelled like a community
        "Path.md": god("Path", 12, "", "core"),
        "notes.md": "# notes\n\nnot an article of graphify\n",
    }


def test_the_flat_export_becomes_an_index_of_folders_then_one_line_per_community(tmp_path):
    (tmp_path / "packages" / "a").mkdir(parents=True)
    (tmp_path / "packages" / "a" / "pyproject.toml").write_text('[project]\nname = "a"\n', encoding="utf-8")
    articles = flat_articles()
    wiki = export(tmp_path, articles)

    done = run(tmp_path)

    assert done.returncode == 0, done.stderr
    assert done.stdout.splitlines()[-1] == (
        "wiki/graph/index.md: 6 communities, 71 nodes, 5 folders, 2 most connected nodes, 0 split"
    )
    assert "skipped notes.md" in done.stderr
    index = (wiki / "index.md").read_text(encoding="utf-8").splitlines()
    assert index[:2] == ["# Code graph", MARK]
    assert index[3].startswith("6 communities, 71 nodes in 5 folders")
    assert [line for line in index if line.startswith("- [")] == [
        "- [packages/a](_index/packages-a.md) — 2 communities, 52 nodes",
        "- [docs](_index/docs.md) — 1 communities, 9 nodes",
        "- [packages](_index/packages.md) — 1 communities, 5 nodes",
        "- [(root)](_index/root.md) — 1 communities, 3 nodes",
        "- [(no source file)](_index/no-source-file.md) — 1 communities, 2 nodes",
        "- [core](core_2.md) — 30 connections · `packages/a/src/a/core.py`",
        "- [Path](Path.md) — 12 connections",
    ]
    assert (wiki / "_index" / "packages-a.md").read_text(encoding="utf-8") == (
        f"# packages/a — 2 communities, 52 nodes\n{MARK}\n\n"
        "- [core](../core.md) — 40 nodes · `packages/a/src/a`\n"
        "- [tests of core](../tests_of_core.md) — 12 nodes · `packages/a/tests`\n"
    )
    pages = {page.name: page.read_text(encoding="utf-8") for page in (wiki / "_index").glob("*.md")}
    assert sorted(pages) == ["docs.md", "no-source-file.md", "packages-a.md", "packages.md", "root.md"]
    assert "- [guide \\[draft\\]](../guide.md) — 9 nodes · `docs`\n" in pages["docs.md"]
    assert "- [helpers](../helpers.md) — 5 nodes · `packages/b`\n" in pages["packages.md"]
    assert "- [noxfile](../noxfile.md) — 3 nodes · `.`\n" in pages["root.md"]
    assert "- [loose](../loose.md) — 2 nodes · no source file\n" in pages["no-source-file.md"]
    for name, text in articles.items():
        assert (wiki / name).read_text(encoding="utf-8") == text, name
    assert dead_links(wiki) == []
    assert max(page.stat().st_size for page in wiki.rglob("*.md")) <= 12_000


def test_every_page_stays_within_12000_bytes_and_reaches_each_community_once(tmp_path):
    articles = {}
    for i in range(300):
        label = f"community {i:03d}" + " with a long generated label" * 3
        articles[f"c{i:03d}.md"] = community(label, 300 - i, [f"docs/part{i:03d}.md"])
    for i in range(150):
        package = f"packages/p{i:03d}-with-a-long-package-name-for-the-index"
        (tmp_path / package).mkdir(parents=True)
        (tmp_path / package / "package.json").write_text("{}\n", encoding="utf-8")
        articles[f"p{i:03d}.md"] = community(f"package {i:03d}", 3, [f"{package}/src/m.ts"])
    wiki = export(tmp_path, articles)

    done = run(tmp_path)

    assert done.returncode == 0, done.stderr
    pages = [wiki / "index.md", *sorted((wiki / "_index").glob("*.md"))]
    assert max(page.stat().st_size for page in pages) <= 12_000
    index = pages[0].read_text(encoding="utf-8")
    assert "](_index/index.1.md)" in index and "](_index/index.2.md)" in index
    assert "](_index/index.3.md)" not in index
    docs = (wiki / "_index" / "docs.md").read_text(encoding="utf-8")
    assert "](docs.1.md)" in docs and "](docs.4.md)" in docs and "](docs.5.md)" not in docs
    reached = [
        target for page in pages[1:] for target in LINK.findall(page.read_text(encoding="utf-8")) if target[:3] == "../"
    ]
    assert sorted(reached) == sorted(f"../{name}" for name in articles)
    assert dead_links(wiki) == []


def test_an_article_over_12000_bytes_is_split_and_its_old_name_still_opens_it(tmp_path):
    concepts = [f"- **{'node with a long name ' * 12}{i}** ({40 - i} connections) — `docs/big.md`" for i in range(25)]
    sources = [f"- `docs/{'deep/' * 50}file{i:02d}.md`" for i in range(20)]
    big = "\n".join(
        [
            "# big",
            "",
            "> 30 nodes · cohesion 0.50",
            "",
            "## Key Concepts",
            "",
            *concepts,
            "",
            "## Relationships",
            "",
            "- [small](small.md) (3 shared connections)",
            "",
            "## Source Files",
            "",
            *sources,
            "",
            FOOTER,
        ]
    )
    assert len(big.encode()) > 12_000
    small = community("small", 3, ["docs/small.md"], links=("big.md",))
    wiki = export(tmp_path, {"big.md": big, "small.md": small})

    done = run(tmp_path)

    assert done.returncode == 0, done.stderr
    assert "split wiki/graph/big.md: " in done.stdout
    assert done.stdout.splitlines()[-1].endswith(", 1 split")
    stub = (wiki / "big.md").read_text(encoding="utf-8")
    assert stub.splitlines()[:3] == ["# big", MARK, "> 30 nodes · cohesion 0.50"]
    assert "](big/README.md)" in stub and len(stub.encode()) <= 12_000
    readme = (wiki / "big" / "README.md").read_text(encoding="utf-8")
    assert re.fullmatch(r"# .+ — index of \d+ parts", readme.splitlines()[0])
    parts = [part for part in (wiki / "big").glob("*.md") if part.name != "README.md"]
    assert len(parts) >= 2 and max(part.stat().st_size for part in parts) <= 12_000
    assert (wiki / "small.md").read_text(encoding="utf-8") == small
    assert dead_links(wiki) == []


def test_an_index_that_graphify_did_not_write_is_refused(tmp_path):
    wiki = tmp_path / "wiki" / "graph"
    wiki.mkdir(parents=True)
    (wiki / "index.md").write_text(f"# Code graph\n{MARK}\n", encoding="utf-8")

    done = run(tmp_path)

    assert done.returncode == 2
    assert "graph_index: wiki/graph/index.md is not graphify's flat index; run bash ops/graph.sh" in done.stderr
    assert not (wiki / "_index").exists()
    (wiki / "index.md").unlink()
    done = run(tmp_path, "wiki/graph")
    assert done.returncode == 2 and "is not graphify's flat index" in done.stderr
